#!/usr/bin/env node
// The API's route table, read from the server's code, so docs/api.md never misses a call.
//   node scripts/gen-api-routes.js                 print the table (Markdown)
//   node scripts/gen-api-routes.js --json          print the routes as JSON
//   node scripts/gen-api-routes.js --write docs/api.md   put the table between the routes markers in that file
//   node scripts/gen-api-routes.js --check docs/api.md   fail when the file is out of date (see check() below)
// Routes are registered with route(method, path, area, fn) in core.js and the modules it plugs in (pro-api.js,
// home.js), and with core.route(...) / R(...) by the modules app.js starts (spotify.js, nowplaying.js, homekit/,
// integrations/). A few answer plain HTTP before the API (handleHttp: Spotify's sign-in redirect, the Stream Deck
// plugin download). Both kinds are found by reading the source; anything that looks like a route but can't be read
// (a path that isn't a string literal) is an error, so a new way of registering routes can't slip past. The table
// links each route to its file, not its line, so it only changes when routes do.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = path.join(ROOT, "packages/server/src");
const METHODS = "GET|POST|PUT|PATCH|DELETE";
const BEGIN = "<!-- routes:begin (generated by scripts/gen-api-routes.js, do not edit by hand) -->", END = "<!-- routes:end -->";

function jsFiles(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap(e => e.isDirectory() ? jsFiles(path.join(dir, e.name)) : e.name.endsWith(".js") && !e.name.endsWith(".test.js") ? [path.join(dir, e.name)] : []);
}
// comments out (kept as spaces, so offsets and line numbers stay right); strings are left alone
function stripComments(s) {
  let out = "", i = 0, q = null;
  while (i < s.length) {
    const c = s[i], n = s[i + 1];
    if (q) { out += c; if (c === "\\") { out += n ?? ""; i += 2; continue; } if (c === q) q = null; i++; continue; }
    if (c === '"' || c === "'" || c === "`") { q = c; out += c; i++; continue; }
    if (c === "/" && n === "/") { while (i < s.length && s[i] !== "\n") { out += " "; i++; } continue; }
    if (c === "/" && n === "*") { while (i < s.length && !(s[i] === "*" && s[i + 1] === "/")) { out += s[i] === "\n" ? "\n" : " "; i++; } out += "  "; i += 2; continue; }
    out += c; i++;
  }
  return out;
}

/** @returns {{method:string, path:string, area:string, file:string, line:number, kind:"api"|"http"}[]} */
export function collectRoutes() {
  const routes = [], errors = [];
  for (const file of jsFiles(SRC).sort()) {
    const src = stripComments(readFileSync(file, "utf8")), rel = path.relative(ROOT, file).split(path.sep).join("/");
    const lineOf = i => src.slice(0, i).split("\n").length;
    // route("GET", "/api/x", area, fn), core.route(...), R(...)
    const re = new RegExp(String.raw`\b(?:route|core\.route|R)\(\s*"(${METHODS})"\s*,\s*"([^"]+)"\s*,\s*(null|"(\w+)")`, "g");
    const found = [];
    for (let m; (m = re.exec(src));) found.push({ i: m.index, method: m[1], path: m[2], area: m[4] || null });
    found.forEach((r, k) => {
      const body = src.slice(r.i, k + 1 < found.length ? found[k + 1].i : src.length); // the handler, roughly: up to the next route
      // routes open to everyone that check something of their own
      let area = r.area === null ? "open" : r.area === "admin" ? "admin" : `guest: ${r.area}`;
      if (r.area === null && /\bphoneOk\(ctx\)/.test(body)) area = "brightness or link key";
      if (r.area === null && /auth\?\.token/.test(body)) area = "game token";
      routes.push({ method: r.method, path: r.path, area, file: rel, line: lineOf(r.i), kind: "api" });
    });
    // anything else that looks like a route registration but wasn't read above
    const loose = new RegExp(String.raw`\b(?:route|core\.route|R)\(\s*(?!"(?:${METHODS})"\s*,\s*"[^"]+"\s*,\s*(?:null|"\w+"))[^)]`, "g");
    for (let m; (m = loose.exec(src));) errors.push(`${rel}:${lineOf(m.index)}: a route whose method, path or area isn't a string literal: ${src.slice(m.index, m.index + 60).split("\n")[0]}`);
    // plain HTTP handlers in front of the API: if (req.method !== "GET" || url.pathname !== "/api/...") return false;
    const http = new RegExp(String.raw`req\.method\s*!==\s*"(${METHODS})"\s*\|\|\s*url\.pathname\s*!==\s*"([^"]+)"`, "g");
    for (let m; (m = http.exec(src));) routes.push({ method: m[1], path: m[2], area: "open", file: rel, line: lineOf(m.index), kind: "http" });
  }
  if (errors.length) { const e = new Error(errors.join("\n")); e.routes = routes; throw e; }
  const seen = new Set();
  for (const r of routes) { const k = `${r.method} ${r.path}`; if (seen.has(k)) throw new Error(`${r.file}:${r.line}: ${k} is registered twice`); seen.add(k); }
  return routes.sort((a, b) => a.path.localeCompare(b.path) || METHODS.split("|").indexOf(a.method) - METHODS.split("|").indexOf(b.method));
}

export function table(routes) {
  const rows = routes.map(r => `| \`${r.method} ${r.path}\` | ${r.area} | [${r.file.replace("packages/server/src/", "")}](../${r.file})${r.kind === "http" ? " (plain HTTP)" : ""} |`);
  return [`${routes.length} routes. Area: **open** needs nothing, **admin** needs an unlock token while a PIN lock is set, **guest: <area>** works`,
    `without one when that guest area is allowed in Settings (see [Auth](#auth)).`, "",
    "| Call | Area | Defined in |", "| --- | --- | --- |", ...rows].join("\n");
}
const block = routes => `${BEGIN}\n${table(routes)}\n${END}`;

/**
 * Problems with a doc: its generated table is out of date, a route in the code isn't described outside the table
 * (written as `METHOD /path` in backticks somewhere in the text), or the text describes a route the code doesn't have.
 */
export function check(doc, routes = collectRoutes()) {
  const problems = [], a = doc.indexOf(BEGIN), b = doc.indexOf(END);
  if (a < 0 || b < a) return [`no generated route table (the ${BEGIN.slice(0, 20)}... and ${END} markers)`];
  if (doc.slice(a, b + END.length) !== block(routes)) problems.push("the generated route table is out of date: run node scripts/gen-api-routes.js --write docs/api.md");
  const text = doc.slice(0, a) + doc.slice(b + END.length);
  const mentioned = new Set([...text.matchAll(new RegExp(String.raw`\`(${METHODS}) (/[^\`\s?]*)`, "g"))].map(m => `${m[1]} ${m[2]}`));
  for (const r of routes) if (!mentioned.has(`${r.method} ${r.path}`)) problems.push(`not described: \`${r.method} ${r.path}\` (${r.file}:${r.line})`);
  const known = new Set(routes.map(r => `${r.method} ${r.path}`));
  for (const k of mentioned) if (k.split(" ")[1].startsWith("/api/") && !known.has(k)) problems.push(`described but not in the code: \`${k}\``);
  return problems;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const args = process.argv.slice(2), at = k => { const i = args.indexOf(k); return i >= 0 ? args[i + 1] : null; };
  let routes; try { routes = collectRoutes(); } catch (e) { console.error(e.message); process.exit(1); }
  if (at("--check")) {
    const f = path.resolve(at("--check")), problems = check(readFileSync(f, "utf8"), routes);
    if (problems.length) { console.error(`${path.relative(process.cwd(), f)}:\n  ${problems.join("\n  ")}`); process.exit(1); }
    console.log(`${path.relative(process.cwd(), f)}: all ${routes.length} routes documented`);
  } else if (at("--write")) {
    const f = path.resolve(at("--write")), doc = readFileSync(f, "utf8"), a = doc.indexOf(BEGIN), b = doc.indexOf(END);
    if (a < 0 || b < a) { console.error(`${f} has no ${END} markers`); process.exit(1); }
    writeFileSync(f, doc.slice(0, a) + block(routes) + doc.slice(b + END.length)); console.log(`${path.relative(process.cwd(), f)}: ${routes.length} routes`);
  } else if (args.includes("--json")) console.log(JSON.stringify(routes, null, 2));
  else console.log(table(routes));
}
