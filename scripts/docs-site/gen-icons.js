#!/usr/bin/env node
// Writes scripts/docs-site/icons.js: the Lucide icons (https://lucide.dev, ISC licence) the docs site uses, so building
// it needs no network and no npm package. Only the icons named somewhere are copied: in mintlify/docs.json, the pages'
// front matter and <Card icon="…">, the API tags (openapi.js TAG_ICONS) and the renderer's own icon("…") calls.
//   git clone --depth 1 https://github.com/lucide-icons/lucide /tmp/lucide
//   node scripts/docs-site/gen-icons.js /tmp/lucide
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { execSync } from "node:child_process";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { TAG_ICONS } from "./openapi.js";

const HERE = path.dirname(fileURLToPath(import.meta.url)), ROOT = path.resolve(HERE, "../.."), SRC = path.join(ROOT, "mintlify");
const lucide = process.argv[2]; if (!lucide || !existsSync(path.join(lucide, "icons"))) { console.error("Usage: node scripts/docs-site/gen-icons.js <a clone of github.com/lucide-icons/lucide>"); process.exit(1); }
// icons the client script and the callouts use by name (not as icon("…") literals)
const UI = ["info", "lightbulb", "triangle-alert", "circle-check", "octagon-alert", "file-text", "hash", "braces", "corner-down-left", "users", "globe", "key-round", "lock", "text"];

const names = new Set(UI);
const walk = d => readdirSync(d, { withFileTypes: true }).flatMap(e => e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]);
const cfg = readFileSync(path.join(SRC, "docs.json"), "utf8"); for (const m of cfg.matchAll(/"icon":\s*"([\w-]+)"/g)) names.add(m[1]);
for (const f of walk(SRC).filter(f => f.endsWith(".mdx"))) { const s = readFileSync(f, "utf8"); for (const m of s.matchAll(/(?:^icon:\s*"?|\bicon=")([\w-]+)/gm)) names.add(m[1]); }
for (const v of Object.values(TAG_ICONS)) names.add(v);
for (const f of [path.join(ROOT, "scripts/build-docs-site.js"), ...walk(HERE).filter(f => f.endsWith(".js") && !f.endsWith("icons.js"))]) for (const m of readFileSync(f, "utf8").matchAll(/\b(?:icon|ic)\("([a-z0-9-]+)"/g)) names.add(m[1]);
names.delete("github"); // a brand mark, not a Lucide icon (below)

// Lucide renames icons now and then and keeps the old names as aliases (in each icon's .json): accept both
const alias = new Map();
for (const j of readdirSync(path.join(lucide, "icons")).filter(f => f.endsWith(".json"))) { try { for (const a of JSON.parse(readFileSync(path.join(lucide, "icons", j), "utf8")).aliases || []) alias.set(typeof a === "string" ? a : a.name, j.slice(0, -5)); } catch {} }
const icons = {}, missing = [];
for (const n of [...names].sort()) {
  let f = path.join(lucide, "icons", n + ".svg"); if (!existsSync(f) && alias.has(n)) f = path.join(lucide, "icons", alias.get(n) + ".svg");
  if (!existsSync(f)) { missing.push(n); continue; }
  icons[n] = readFileSync(f, "utf8").replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").replace(/\s*\n\s*/g, "").trim();
}
if (missing.length) { console.error(`Not in Lucide: ${missing.join(", ")}`); process.exit(1); }
let rev = ""; try { rev = execSync("git rev-parse --short HEAD", { cwd: lucide }).toString().trim(); } catch {}
const licence = readFileSync(path.join(lucide, "LICENSE"), "utf8").split("\n---")[0].trim();
writeFileSync(path.join(HERE, "icons.js"), `// Generated by scripts/docs-site/gen-icons.js from Lucide${rev ? ` (github.com/lucide-icons/lucide ${rev})` : ""}: only the icons the docs site uses.
// Each value is the inside of a 24x24 <svg> drawn with stroke="currentColor". Regenerate after adding an icon to a page.
/*
Lucide icons: https://lucide.dev
${licence.replace(/\*\//g, "* /")}

Some Lucide icons are derived from Feather (https://feathericons.com), MIT licence, copyright (c) 2013-present Cole Bemis.

The GitHub mark (BRANDS.github) is from GitHub's Octicons (https://primer.style/octicons), MIT licence, copyright (c) GitHub Inc.
*/
export const ICONS = ${JSON.stringify(icons, null, 0).replace(/","/g, '",\n  "').replace(/^\{/, "{\n  ").replace(/\}$/, "\n}")};

export const BRANDS = {
  github: { viewBox: "0 0 24 24", body: '<path d="M10.226 17.284c-2.965-.36-5.054-2.493-5.054-5.256 0-1.123.404-2.336 1.078-3.144-.292-.741-.247-2.314.09-2.965.898-.112 2.111.36 2.83 1.01.853-.269 1.752-.404 2.853-.404 1.1 0 1.999.135 2.807.382.696-.629 1.932-1.1 2.83-.988.315.606.36 2.179.067 2.942.72.854 1.101 2 1.101 3.167 0 2.763-2.089 4.852-5.098 5.234.763.494 1.28 1.572 1.28 2.807v2.336c0 .674.561 1.056 1.235.786 4.066-1.55 7.255-5.615 7.255-10.646C23.5 6.188 18.334 1 11.978 1 5.62 1 .5 6.188.5 12.545c0 4.986 3.167 9.12 7.435 10.669.606.225 1.19-.18 1.19-.786V20.63a2.9 2.9 0 0 1-1.078.224c-1.483 0-2.359-.808-2.987-2.313-.247-.607-.517-.966-1.034-1.033-.27-.023-.359-.135-.359-.27 0-.27.45-.471.898-.471.652 0 1.213.404 1.797 1.235.45.651.921.943 1.483.943.561 0 .92-.202 1.437-.719.382-.381.674-.718.944-.943"/>' },
};
`);
console.log(`scripts/docs-site/icons.js: ${Object.keys(icons).length} Lucide icons + the GitHub mark`);
